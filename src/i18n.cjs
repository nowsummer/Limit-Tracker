let current = 'ko';
function resolveLanguage(setting, locale = '') {
  if (LANGUAGES.includes(setting)) return setting;
  return /^ko\b/i.test(String(locale || '')) ? 'ko' : 'en';
}
function setLanguage(language) { current = LANGUAGES.includes(language) ? language : 'ko'; return current; }
function getLanguage() { return current; }
function format(text, params) {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(params, key) ? String(params[key]) : match);
}
function t(key, params, language = current) {
  const entry = STRINGS[key];
  if (!entry) return key;
  return format(entry[language === 'en' ? 1 : 0], params);
}
module.exports = { LANGUAGES, STRINGS, t, format, setLanguage, getLanguage, resolveLanguage };
