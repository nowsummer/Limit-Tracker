  const LANGUAGES = ['ko', 'en'];
  let current = 'ko';
  function format(text, params) {
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(params, key) ? String(params[key]) : match);
  }
  function t(key, params) {
    const entry = STRINGS[key];
    if (!entry) return key;
    return format(entry[current === 'en' ? 1 : 0], params);
  }
  function resolve(setting, navigatorLanguage) {
    if (LANGUAGES.includes(setting)) return setting;
    return /^ko\b/i.test(String(navigatorLanguage || '')) ? 'ko' : 'en';
  }
  function setLanguage(language) {
    const next = LANGUAGES.includes(language) ? language : 'ko';
    const changed = next !== current;
    current = next;
    if (typeof document !== 'undefined' && document.documentElement) document.documentElement.lang = current;
    return changed;
  }
  function getLanguage() { return current; }
  /** Applies data-i18n, data-i18n-title, data-i18n-aria-label and data-i18n-placeholder attributes. */
  function apply(root = document) {
    for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
    for (const node of root.querySelectorAll('[data-i18n-title]')) node.title = t(node.dataset.i18nTitle);
    for (const node of root.querySelectorAll('[data-i18n-aria-label]')) node.setAttribute('aria-label', t(node.dataset.i18nAriaLabel));
    for (const node of root.querySelectorAll('[data-i18n-placeholder]')) node.placeholder = t(node.dataset.i18nPlaceholder);
    // Paragraph groups: each line of the text becomes its own block.
    for (const node of root.querySelectorAll('[data-i18n-lines]')) {
      node.replaceChildren(...t(node.dataset.i18nLines).split('\n').filter(Boolean).map(line => { const part = document.createElement('span'); part.className = 'info-line'; part.textContent = line; return part; }));
    }
    for (const node of root.querySelectorAll('[data-i18n-html]')) {
      // Only two line-broken paragraphs use this; content is static dictionary text.
      node.replaceChildren(...t(node.dataset.i18nHtml).split('\n').flatMap((line, index) => index ? [document.createElement('br'), line] : [line]));
    }
  }
  window.LimitI18n = { STRINGS, LANGUAGES, t, format, resolve, setLanguage, getLanguage, apply };
